export function translate(
  lang: AppLanguage,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[lang] ?? EN_TRANSLATIONS;
  let value = dict[key] ?? EN_TRANSLATIONS[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}
